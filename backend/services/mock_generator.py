import time
import uuid
from datetime import datetime, timezone
from backend.services.base_generator import BaseGenerator
from backend.schemas import GenerationRequest, GenerationResponse, GenerationMetadata


# Map palette mặc định theo profile_id
PROFILE_PALETTES = {
    "medieval-pixel-art": "pico-8-medieval",
    "cyberpunk-neon": "neon-cyber-16",
    "retro-gameboy": "gameboy-classic-4"
}


class MockGenerator(BaseGenerator):
    """
    Mock Generator giả lập phản hồi của hệ thống AI Pixel Art.
    Được sử dụng cho TASK-001 để kiểm thử Frontend - Backend,
    trước khi tích hợp mô hình AI thực tế ở TASK-002.
    """

    @property
    def generator_type(self) -> str:
        return "mock"

    def generate(self, request: GenerationRequest) -> GenerationResponse:
        start_time = time.perf_counter()

        # Giả lập thời gian xử lý nhanh (khoảng vài mili-giây)
        time.sleep(0.05)

        # Chọn ảnh mẫu theo canvas_size đã cấu hình sẵn
        size = request.canvas_size if request.canvas_size in (64, 128, 256) else 64
        sample_filename = f"sample_{size}.png"
        image_url = f"/static/samples/{sample_filename}"

        # Xác định palette
        palette = PROFILE_PALETTES.get(request.profile_id, "default-palette")

        elapsed_ms = int((time.perf_counter() - start_time) * 1000)
        generation_id = f"gen_mock_{uuid.uuid4().hex[:8]}"
        created_at_iso = datetime.now(timezone.utc).isoformat()

        return GenerationResponse(
            id=generation_id,
            status="success",
            prompt=request.prompt,
            profile_id=request.profile_id,
            canvas_size=request.canvas_size,
            image_url=image_url,
            generator_type="mock",
            created_at=created_at_iso,
            metadata=GenerationMetadata(
                palette_used=palette,
                inference_time_ms=elapsed_ms,
                note="Generated by MockGenerator (TASK-001). Sẵn sàng thay thế bằng AI Generator trong TASK-002."
            )
        )
